#!/usr/bin/env python3
"""Build handbook/data/seh-nl.json from the RIVM questionnaire spreadsheet.

Source: RIVM, "Vragenlijst aanbod SEH's en Acute Verloskunde" (open data, no
use restrictions), https://data.rivm.nl/meta/srv/dut/catalog.search#/metadata/afbdf4b9-00f0-4d4e-a67e-fd3bbc8c833c
Download the zip there, unpack it, then:

    python3 -I handbook/scripts/seh_from_rivm.py "<path to .xlsx>" handbook/data/seh-nl.json

Standard library only. Each address is looked up at PDOK by postcode and
house number; a location that cannot be matched on its exact postcode stops
the script, so a wrong pin never ends up in the table silently.
"""
import datetime
import json
import re
import sys
import time
import urllib.parse
import urllib.request
import xml.etree.ElementTree as ET
import zipfile

M = 'http://schemas.openxmlformats.org/spreadsheetml/2006/main'
R = 'http://schemas.openxmlformats.org/officeDocument/2006/relationships'
SHEET = 'Reguliere vragenlijst'


def sheets(path):
    z = zipfile.ZipFile(path)
    strings = [''.join(t.text or '' for t in si.iter('{%s}t' % M)) for si in ET.fromstring(z.read('xl/sharedStrings.xml')).findall('{%s}si' % M)]
    rels = {r.get('Id'): r.get('Target') for r in ET.fromstring(z.read('xl/_rels/workbook.xml.rels'))}
    out = {}
    for sh in ET.fromstring(z.read('xl/workbook.xml')).find('{%s}sheets' % M):
        target = rels[sh.get('{%s}id' % R)]
        target = target.lstrip('/') if target.startswith('/') else 'xl/' + target
        rows = []
        for row in ET.fromstring(z.read(target)).iter('{%s}row' % M):
            cells = {}
            for c in row.findall('{%s}c' % M):
                v = c.find('{%s}v' % M)
                text = '' if v is None else strings[int(v.text)] if c.get('t') == 's' else v.text
                cells[re.match(r'[A-Z]+', c.get('r')).group(0)] = clean(text)
            rows.append(cells)
        out[sh.get('name')] = rows
    return out


def clean(text):
    return re.sub(r'\s+', ' ', (text or '').replace('_x000D_', ' ')).strip()


def pdok(params):
    url = 'https://api.pdok.nl/bzk/locatieserver/search/v3_1/free?' + urllib.parse.urlencode(params)
    req = urllib.request.Request(url, headers={'User-Agent': 'kit72-handbook-proof/0.1'})
    with urllib.request.urlopen(req, timeout=30) as res:
        return json.load(res)['response']['docs']


def locate(address, postcode):
    """(lat, lon, how) for a postcode and house number; how says what matched."""
    pc = postcode.replace(' ', '').upper()
    number = re.search(r'\d+', address)
    docs = pdok({'q': f'{pc} {number.group(0)}', 'fq': 'type:adres', 'rows': 5}) if number else []
    doc = next((d for d in docs if d.get('postcode') == pc), None)
    how = 'adres'
    if not doc:
        docs = pdok({'q': pc, 'fq': 'type:postcode', 'rows': 1})
        doc = next((d for d in docs if d.get('postcode') == pc), None)
        how = 'postcode'
    if not doc:
        raise SystemExit(f'Niet gevonden bij PDOK: {address}, {postcode}')
    lon, lat = (float(v) for v in re.findall(r'-?\d+\.\d+', doc['centroide_ll']))
    return round(lat, 6), round(lon, 6), how


def main(xlsx, out):
    book = sheets(xlsx)
    version = next((r['A'] for r in book['Leeswijzer'] if r.get('A', '').startswith('Datum')), '')
    rows = book[SHEET]
    head = next(i for i, r in enumerate(rows) if r.get('A') == 'Naam ziekenhuis')
    locations = []
    for r in rows[head + 1:]:
        if not r.get('A'):
            continue
        answer = r.get('H', '')
        if '24/7' in answer and 'niet 24/7' not in answer:
            hours = {'allDay': True}
        elif 'niet 24/7' in answer:
            # columns I, J, K are filled for the parts of the day the department is open
            hours = {'allDay': False, 'day': bool(r.get('I')), 'evening': bool(r.get('J')), 'night': bool(r.get('K'))}
            if r.get('L'):
                hours['note'] = r['L']
        else:
            raise SystemExit(f"Onbekend antwoord op openingstijden voor {r['A']}: {answer!r}")
        lat, lon, how = locate(r.get('C', ''), r.get('D', ''))
        locations.append({'name': r['A'], 'place': r.get('B', ''), 'address': r.get('C', ''), 'postcode': r.get('D', ''), 'lat': lat, 'lon': lon, 'located': how, **hours})
        time.sleep(0.15)
    data = {
        '_note': 'Hospital locations with an emergency department (SEH), from the answers hospitals gave RIVM. Generated by handbook/scripts/seh_from_rivm.py; do not edit by hand.',
        'source': {
            'title': "RIVM Vragenlijst aanbod SEH's en Acute Verloskunde 2026",
            'url': 'https://data.rivm.nl/meta/srv/dut/catalog.search#/metadata/afbdf4b9-00f0-4d4e-a67e-fd3bbc8c833c',
            'version': re.sub(r'[^0-9-]', '', version),
            'licence': 'Geen beperkingen (RIVM)',
        },
        'checked': datetime.date.today().isoformat(),
        'locations': locations,
    }
    with open(out, 'w', encoding='utf-8') as f:
        json.dump(data, f, ensure_ascii=False, indent=1)
        f.write('\n')
    limited = [x['name'] for x in locations if not x['allDay']]
    by_postcode = [x['name'] for x in locations if x['located'] == 'postcode']
    print(f'{len(locations)} locaties, {len(limited)} niet dag en nacht open: {", ".join(limited)}')
    print(f'Op postcode in plaats van adres geplaatst: {", ".join(by_postcode) or "geen"}')


if __name__ == '__main__':
    main(sys.argv[1], sys.argv[2])
